"""Eval dataset: sessions to classify and the human labels for them.

Sessions are stored as Messages API request/response bodies, so they go through the same
digest code (gateway/digest.py) as live gateway traffic.

    evals/data/synthetic_sessions.jsonl  generated by generate_synthetic.py (committed)
    evals/data/real/sessions.jsonl       exported from the gateway by export_real.py
                                         (gitignored: real conversations stay private)
    evals/data/labels.jsonl              one human label per session id (committed)

The labels are the ground truth. A synthetic session's `generator` field records what the
generator was asked to produce, which is not a label: labeling is blind to it.
"""

import json
import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from gateway.digest import build_digest

DATA_DIR = Path(__file__).resolve().parent / "data"
SYNTHETIC_PATH = DATA_DIR / "synthetic_sessions.jsonl"
REAL_PATH = DATA_DIR / "real" / "sessions.jsonl"
LABELS_PATH = DATA_DIR / "labels.jsonl"


@dataclass
class EvalSession:
    id: str
    source: str  # "synthetic" | "real"
    requests: list[dict[str, Any]]
    responses: list[dict[str, Any] | None] = field(default_factory=list)
    generator: dict[str, Any] | None = None  # synthetic only; hidden while labeling

    @property
    def digest(self) -> str:
        return build_digest(self.requests, self.responses)

    def to_json(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "source": self.source,
            "requests": self.requests,
            "responses": self.responses,
            "generator": self.generator,
        }


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))


def load_sessions() -> list[EvalSession]:
    sessions = [EvalSession(**r) for r in read_jsonl(SYNTHETIC_PATH) + read_jsonl(REAL_PATH)]
    ids = [s.id for s in sessions]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate session ids in the eval dataset")
    return sessions


def load_labels(categories_version: int) -> dict[str, str]:
    """Session id -> label, using only labels made under this categories version (labels
    made under different definitions would measure the wrong thing). A later line for the
    same id replaces an earlier one."""
    return {
        r["id"]: r["label"]
        for r in read_jsonl(LABELS_PATH)
        if r.get("categories_version", 1) == categories_version
    }


def label_provenance(categories_version: int) -> dict[str, int]:
    """How the labels in use were made: labeled fresh under this version, or copied from
    an earlier version's labels (made under different definitions)."""
    latest = {
        r["id"]: r
        for r in read_jsonl(LABELS_PATH)
        if r.get("categories_version", 1) == categories_version
    }
    copied = sum("copied_from_version" in r for r in latest.values())
    return {"labeled_under_this_version": len(latest) - copied, "copied_from_earlier": copied}


def split(session_id: str, seed: int = 0) -> str:
    """Deterministic 50/50 "dev"/"test" split: tune prompts on dev, report test."""
    return "dev" if random.Random(f"{seed}:{session_id}").random() < 0.5 else "test"
